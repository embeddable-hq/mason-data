/**
 * `text` with its generated block — from the first of `starts` it has to the END after it — replaced by `rendered`; a
 * text with none gets the block before the line `insertBefore` when one is named and it has that line; else null.
 */
export function spliceGenerated(text: string, starts: readonly string[], rendered: string, insertBefore?: string): string | null {
  const found = starts.map((s) => text.indexOf(s)).filter((i) => i >= 0);
  if (found.length === 0) {
    const at = insertBefore === undefined ? -1 : text.indexOf(insertBefore);
    return at < 0 ? null : `${text.slice(0, at)}${rendered}${END}\n\n${text.slice(at)}`;
  }
  const a = Math.min(...found), z = text.indexOf(END, a);
  return z < 0 ? null : text.slice(0, a) + rendered + text.slice(z);
}

/**
 * The lines from one of `starts` to the END after it in `file` are `rendered`, from `from` (a fixture). With
 * UPDATE_FIXTURE=1 a block that is missing is written before the line `insertBefore`, when one is named.
 */
function heldToFixture(file: string, starts: readonly string[], rendered: string, from: string, insertBefore?: string): void {
  const name = path.relative(ROOT, file);
  const was = fs.readFileSync(file, "utf8");
  const out = spliceGenerated(was, starts, rendered, UPDATE ? insertBefore : undefined);
  assert.ok(out !== null, `${name} has the lines ${starts[0]} … ${END}`);
  if (UPDATE) { fs.writeFileSync(file, out); console.log(`UPDATE_FIXTURE=1: wrote ${file}`); return; }
  assert.equal(was, out, `${name}'s section is not what ${from} renders: regenerate with \`UPDATE_FIXTURE=1 npm run check\` and read the diff`);
}

