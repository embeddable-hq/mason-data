/** a cold fixture of synthetic numbers, for the renderer: Postgres's time 10 × Mason's for the scans, Mason's 5 × Postgres's for the lookup */
function syntheticCold(sizes: number[], clients: number[], runs: number): ColdFixture {
  const ms = (statement: string, engine: "postgres" | "mason", rows: number, c: number, run: number): number =>
    (statement === "lookup" ? (engine === "postgres" ? 2 : 10) : (engine === "postgres" ? 1000 : 100)) * (rows / 1e6) * (c === 1 ? 1 : 2) + run;
  return {
    kind: "cold",
    environment: {
      label: "a test box", date: "2026-11-17T00:00:00.000Z",
      machine: { cpus: 4, cpuModel: "a test CPU", ramBytes: 16 * 2 ** 30, os: "Linux 6", arch: "arm64", docker: "29.0.0", cgroup: "2" },
      limits: { cpus: 4, memoryBytes: 8 * 2 ** 30, memorySwapBytes: 8 * 2 ** 30 },
      postgres: { image: "postgres:18", version: "PostgreSQL 18.7 (Debian) on aarch64", settings: { shared_buffers: "2048MB", work_mem: "32MB" } },
      mason: { image: "ghcr.io/embeddable-hq/mason-data:0.23.0", version: "0.23.0", serverVersion: "PostgreSQL 18.6 (mason-data 0.23.0)", settings: {}, engineMemory: "half the container's --memory" },
      client: { image: "postgres:18", pgbench: "pgbench (PostgreSQL) 18.7", how: "pgbench -n -c N -j N -t 1" },
      method: { sizes, clients, runs, settleSeconds: 10, timeZone: "UTC", cold: "before every run the engine was restarted", isolation: "the other engine stopped or idle", commit: "abc" },
    },
    statements: COLD_STATEMENTS.map((s) => ({ name: s.name, title: s.title, sql: s.sql })),
    sizes: sizes.map((rows) => ({ rows, customers: rows / 20, lookupIds: Array.from({ length: Math.max(...clients) }, (_, i) => i + 1), generatedSeconds: 1, postgresBytes: rows * 362,
      syncSeconds: 3, masonBytes: rows * 70, answers: Object.fromEntries(COLD_STATEMENTS.map((s) => [s.name, { postgres: "a", mason: "a" }])) })),
    runs: sizes.flatMap((rows) => clients.flatMap((c) => COLD_STATEMENTS.flatMap((s) => (["postgres", "mason"] as const).flatMap((engine) =>
      Array.from({ length: runs }, (_, i): ColdRun => {
        const slowestMs = ms(s.name, engine, rows, c, i);
        return { rows, clients: c, statement: s.name, engine, run: i + 1, at: "2026-11-17T00:00:00.000Z", readySeconds: 1,
          latenciesMs: Array.from({ length: c }, (_, k) => k === 0 ? slowestMs : slowestMs / 2), slowestMs, meanMs: c === 1 ? slowestMs : (slowestMs + slowestMs / 2 * (c - 1)) / c, spanMs: slowestMs };
      }))))),
    complete: true,
  };
}

