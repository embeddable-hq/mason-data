/** A SQLSTATE a reader of the README can place: Postgres's condition name beside the code it recorded (the fixture keeps
 *  the code alone), for the codes a bench has met; any other code is printed as it is. */
function sqlstateName(code: string): string {
  const names: Record<string, string> = { "53100": "disk_full", "53200": "out_of_memory", "53300": "too_many_connections", "57014": "query_canceled", "57P01": "admin_shutdown", "08006": "connection_failure" };
  return code in names ? `${code} ${names[code]}` : code;
}

