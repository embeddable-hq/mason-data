const rowsText = (n: number): string => n.toLocaleString("en-US");
/** a count in a label: 1,000,000 as "1 M", 500,000 as "500 k" (a table about sizes keeps `rowsText`'s whole number) */
export const countText = (n: number): string => n >= 1e6 ? `${Number((n / 1e6).toPrecision(3))} M` : n >= 1e3 ? `${Number((n / 1e3).toPrecision(3))} k` : String(n);
/** a number by its size: 100 or more with no decimals, 10 or more with one, 1 or more with two, under 1 with two significant digits */
export const numText = (x: number): string => !Number.isFinite(x) ? "–" : x === 0 ? "0" :
  x >= 99.5 ? x.toFixed(0) : x >= 9.995 ? x.toFixed(1) : x >= 0.995 ? x.toFixed(2) : x.toPrecision(2);
/** a time, from the fixture's milliseconds, in the section's one unit: seconds */
export const secondsText = (ms: number): string => numText(ms / 1000);
/** the cold tables' numbers: as `numText`, and under 1 with three significant digits, as one of 1 or more has */
export const coldNumText = (x: number): string => !Number.isFinite(x) ? "–" : x === 0 ? "0" : x >= 0.9995 ? numText(x) : x.toPrecision(3);
/** a time in the cold tables, in seconds, by `coldNumText` */
export const coldSecondsText = (ms: number): string => coldNumText(ms / 1000);
/** the last column wherever the two engines are side by side: Mason's time against Postgres's, "15× faster" or "79× slower" */
export function masonIs(postgresMs: number, masonMs: number): string {
  if (!(Number.isFinite(postgresMs) && Number.isFinite(masonMs) && postgresMs > 0 && masonMs > 0)) return "–";
  const r = Math.max(postgresMs, masonMs) / Math.min(postgresMs, masonMs);
  // "1.0× slower" says nothing a reader can use
  if (r < 1.05) return "as fast";
  return `${r < 9.95 ? r.toFixed(1) : r.toFixed(0)}× ${masonMs < postgresMs ? "faster" : "slower"}`;
}
/** words the fixture holds (a sweep's `stopped`, written by the script in ms or s) in the section's one unit */
const inSeconds = (text: string): string =>
  text.replace(/(\d+(?:\.\d+)?) (ms|s)\b/g, (_, n: string, unit: string) => `${secondsText(unit === "ms" ? Number(n) : Number(n) * 1000)} s`);
const gib = (b: number): string => `${(b / 2 ** 30).toFixed(b < 2 ** 30 ? 2 : 1)} GiB`;
const clientsText = (c: number): string => `${c} client${c === 1 ? "" : "s"}`;
const listText = (xs: readonly string[]): string => xs.length <= 1 ? xs.join("") : `${xs.slice(0, -1).join(", ")} and ${xs[xs.length - 1]}`;
const uniq = (xs: number[]): number[] => [...new Set(xs)].sort((a, b) => a - b);
/** a markdown table; an empty header cell stays one space wide */
const table = (head: readonly string[], align: readonly string[], rows: readonly string[][]): string =>
  [`|${head.map((h) => h === "" ? " " : ` ${h} `).join("|")}|`, `|${align.join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

/** the client count the per-statement table is read at: 32, else the most at or under 32, else the fewest */
export function perStatementClients(clients: readonly number[]): number {
  if (clients.includes(32)) return 32;
  const under = clients.filter((c) => c <= 32);
  return under.length ? Math.max(...under) : Math.min(...clients);
}

