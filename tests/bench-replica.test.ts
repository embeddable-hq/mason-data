function renderReplica(f: Fixture): { section: string; headline: string } {
  const env = f.environment;
  type Engine = "postgres" | "mason";
  const find = (rows: number, clients: number, engine: Engine, query: string): Cell | undefined =>
    f.cells.find((x) => x.rows === rows && x.clients === clients && x.engine === engine && x.query === query);
  const cell = (rows: number, clients: number, engine: Engine, query: string): Cell => {
    const c = find(rows, clients, engine, query);
    if (c === undefined) throw new Error(`the fixture has no cell for ${rows} rows, ${clients} clients, ${engine}, ${query}`);
    return c;
  };
  const mixes = f.cells.filter((c) => c.query === "mix");
  if (mixes.length === 0) throw new Error("the fixture measured no cell");
  const sizes = uniq(mixes.map((c) => c.rows)), clients = uniq(mixes.map((c) => c.clients));
  const largest = Math.max(...sizes), at = perStatementClients(uniq(mixes.filter((c) => c.rows === largest).map((c) => c.clients)));
  const titled = new Map(f.queries.map((q) => [q.name, q.title]));
  const titleOf = (q: string): string => `"${titled.get(q) ?? q}"`;
  const where = (rows: number, c: number): string => `${countText(rows)} rows, ${clientsText(c)}`;
  const target = env.method.targetPostgresSeconds;
  const rowsSweep = target === null ? null : f.sweeps?.rows ?? null, clientsSweep = target === null ? null : f.sweeps?.clients ?? null;
  const s = env.postgres.settings;

  // the two lines the section reads along: each sweep's steps, or for a grid the sizes at the per-statement client count
  // and the client counts at the largest size; a measured cell on neither has a table of its own
  const rowsAt = rowsSweep?.clients ?? at, clientsAt = clientsSweep?.rows ?? largest;
  const rowsLine = (rowsSweep?.steps ?? sizes.filter((r) => find(r, at, "postgres", "mix") !== undefined)).map((r): [number, number] => [r, rowsAt]);
  const clientsLine = (clientsSweep?.steps ?? clients.filter((c) => find(largest, c, "postgres", "mix") !== undefined)).map((c): [number, number] => [clientsAt, c]);
  const key = ([r, c]: readonly [number, number]): string => `${r} ${c}`;
  const shown = new Set([...rowsLine, ...clientsLine].map(key));
  const others = [...new Map(mixes.map((c): [string, [number, number]] => [key([c.rows, c.clients]), [c.rows, c.clients]])).values()]
    .filter((rc) => !shown.has(key(rc))).sort((a, b) => a[0] - b[0] || a[1] - b[1]);

  // a mix cell's p95s, the ratio and both rates; – where an engine was not measured there
  const mixRow = (rows: number, c: number): string[] => {
    const p = find(rows, c, "postgres", "mix"), m = find(rows, c, "mason", "mix");
    return [secondsText(p?.p95Ms ?? NaN), secondsText(m?.p95Ms ?? NaN), masonIs(p?.p95Ms ?? NaN, m?.p95Ms ?? NaN), numText(p?.qps ?? NaN), numText(m?.qps ?? NaN)];
  };
  const mixHead = ["Postgres p95 (s)", "Mason p95 (s)", "Mason is", "Postgres statements/s", "Mason statements/s"];
  const mixAlign = ["---:", "---:", "---", "---:", "---:"];

  // a sweep's verdict, under its table: the cell that reached the target, or what stopped the sweep, and Postgres's slowest statement there
  const verdict = (v: SweepVerdict | null): string => {
    if (v === null || target === null) return "";
    const a = v.at;
    const slowest = a === null ? "" : `its slowest statement, ${titleOf(a.slowest.query)}, took ${secondsText(a.slowest.p50Ms)} s at p50`;
    if (v.reached !== null && a !== null) return `\n\nPostgres's p95 reached the ${target} s target at ${where(a.rows, a.clients)}, where ${slowest}.`;
    const stopped = inSeconds(v.stopped ?? "the sweep stopped");
    return `\n\n${stopped.charAt(0).toUpperCase()}${stopped.slice(1)}, before Postgres's p95 reached the ${target} s target` +
      (a === null ? "." : `; at ${where(a.rows, a.clients)}, the last cell measured, ${slowest}.`);
  };

  // the short version: the first and last cell along the rows, the last along the clients, and the point lookup at the largest cell
  const glance: Array<[number, number]> = [];
  for (const rc of [rowsLine[0], rowsLine[rowsLine.length - 1], clientsLine[clientsLine.length - 1]]) {
    if (rc !== undefined && !glance.some((g) => key(g) === key(rc))) glance.push(rc);
  }
  const lookup = f.queries.find((q) => /\$1\b/.test(q.sql));
  const lp = lookup === undefined ? undefined : cell(largest, at, "postgres", lookup.name), lm = lookup === undefined ? undefined : cell(largest, at, "mason", lookup.name);
  const lookupSlower = lp !== undefined && lm !== undefined && lm.p50Ms > lp.p50Ms;
  const shortTable = table(["", "Postgres p95 (s)", "Mason p95 (s)", "Mason is"], ["---", "---:", "---:", "---"], [
    ...glance.map(([r, c]) => [where(r, c), ...mixRow(r, c).slice(0, 3)]),
    ...(lookup === undefined || lp === undefined || lm === undefined ? [] :
      [[`${lookup.title}, ${where(largest, at)} (p50)`, secondsText(lp.p50Ms), secondsText(lm.p50Ms), masonIs(lp.p50Ms, lm.p50Ms)]]),
  ]);
  /** `design` is the link to docs/DESIGN.md from where the note is printed */
  const shortNote = (design: string): string => `Mason is for scans and aggregates${lookupSlower ? `. A lookup through an index is faster on Postgres ([docs/DESIGN.md](${design}) "Heap order, no index")` : ""}.`;

  const rowsContext = `**At ${clientsText(rowsAt)}**, ${rowsSweep !== null ? "a dashboard's concurrency, the tables growing about √10 a step" : "every size measured"}. ` +
    `Each p95 is of the mix: the ${f.queries.length} statements below, each client running them in turn.`;
  const rowsTable = table(["rows", ...mixHead], ["---:", ...mixAlign], rowsLine.map(([r, c]) => [rowsText(r), ...mixRow(r, c)]));
  const clientsContext = `**At ${rowsText(clientsAt)} orders**, ${clientsSweep !== null ? clientsSweep.rowsWhy ?? "the size chosen" : "the largest size measured"}.`;
  const clientsTable = table(["clients", ...mixHead], ["---:", ...mixAlign], clientsLine.map(([r, c]) => [String(c), ...mixRow(r, c)]));
  const connections = clientsSweep !== null && s.max_connections !== undefined
    ? `\n\nThe bench's Postgres allows ${s.max_connections} connections so that every client is answered; Postgres's default is 100, and past a replica's own limit the next connection is refused (53300).`
    : "";
  const otherCells = others.length === 0 ? "" : `
## Every other cell measured

${table(["rows", "clients", ...mixHead], ["---:", "---:", ...mixAlign], others.map(([r, c]) => [rowsText(r), String(c), ...mixRow(r, c)]))}
`;

  const perQuery = f.queries.map((q) => ({ q, p: cell(largest, at, "postgres", q.name), m: cell(largest, at, "mason", q.name) }));
  const perQueryTable = table(["statement", "Postgres p50 (s)", "Postgres p95 (s)", "Mason p50 (s)", "Mason p95 (s)", "Mason is"], ["---", "---:", "---:", "---:", "---:", "---"],
    perQuery.map(({ q, p, m }) => [q.title, secondsText(p.p50Ms), secondsText(p.p95Ms), secondsText(m.p50Ms), secondsText(m.p95Ms), masonIs(p.p50Ms, m.p50Ms)]));
  const postgresWins = perQuery.filter(({ p, m }) => m.p50Ms > p.p50Ms).map(({ q }) => `"${q.title}"`);
  const winsNote = postgresWins.length === 0 ? "Mason answers every statement faster here, at p50." :
    `Postgres is faster at ${listText(postgresWins)}: it reads ${postgresWins.length === 1 ? "it" : "them"} through an index, and Mason's synced tables have none ([docs/DESIGN.md](DESIGN.md) "Heap order, no index").`;

  const copyTable = table(["rows", "in Postgres", "synced in (s)", "on Mason's disk", "JSON path stored after (s)"], ["---:", "---:", "---:", "---:", "---:"],
    f.sizes.map((z) => [`${rowsText(z.rows)} orders, ${rowsText(z.customers)} customers`, gib(z.postgresBytes), numText(z.copySeconds), gib(z.masonFileBytes),
      z.jsonPathReadySeconds === null ? "not stored" : numText(z.jsonPathReadySeconds)]));

  const failed = mixes.filter((c) => c.errors > 0)
    .map((c) => `${rowsText(c.rows)} rows, ${clientsText(c.clients)}, ${c.engine === "postgres" ? "Postgres" : "Mason"}: ${c.errors} (${Object.entries(c.errorCodes).map(([k, n]) => `${sqlstateName(k)} × ${n}`).join(", ")})`);
  const differing = f.sizes.filter((z) => !z.answersEqual);
  const pgMemory = env.postgres.containerMemoryBytes === null ? "" : `, ${gib(env.postgres.containerMemoryBytes)} of memory`;
  const pgVersion = /^PostgreSQL [\d.]+/.exec(env.postgres.version)?.[0] ?? env.postgres.version;
  const settings = ["shared_buffers", "effective_cache_size", "work_mem", "max_parallel_workers_per_gather", "max_connections"].filter((k) => s[k] !== undefined).map((k) => `${k} ${s[k]}`).join(", ");
  const windows = uniq(mixes.map((c) => c.seconds));
  const windowText = windows.length === 1 ? `${windows[0]} s` : `${windows[0]}–${windows[windows.length - 1]} s (3 × the target after a cell where Postgres took over a tenth of it)`;
  const measuredOn = `Measured on ${env.label}: ${env.machine.cpus} CPUs (${env.machine.cpuModel}), ${gib(env.machine.ramBytes)} of RAM, ${env.machine.os}; ` +
    `${pgVersion}, ${env.postgres.where}${pgMemory} (${settings}); ` +
    `Mason ${env.mason.commit} with DuckDB ${env.mason.duckdb} at ${env.mason.memoryLimit}; ${env.date.slice(0, 10)}.`;
  const method = `Synthetic rows (an \`orders\` table with a jsonb payload, and \`customers\`, from \`generate_series\`); ` +
    (target === null ? `a grid of sizes and client counts; ` : `each axis pushed until Postgres's p95 reached ${target} s; `) +
    `each cell measured for ${windowText} after a warm-up of ${env.method.warmupSeconds} s and one pass of the mix by every client, the median of ` +
    `${env.method.runs} run${env.method.runs === 1 ? "" : "s"}; ${env.method.isolation}.`;
  const measured = [
    measuredOn,
    method,
    differing.length === 0 ? "Every statement's answer was the same on both, compared before each size was measured." :
      `Answers that differed before measuring: ${differing.map((d) => `${rowsText(d.rows)} rows: ${d.differences.join("; ")}`).join(" ")}`,
    ...(failed.length === 0 ? [] : [`Statements that failed, counted in neither the latency nor the rate: ${failed.join("; ")}.`]),
    ...(f.skipped.length === 0 ? [] : [`Not measured: ${f.skipped.map((k) => `${rowsText(k.rows)} rows (${k.why})`).join("; ")}.`]),
    "To rerun: `node scripts/bench-replica.ts` ([docs/BENCHMARK.md](BENCHMARK.md) says how, and how to publish a result here).",
  ].join("\n\n");

  // the headline's lead: the range of the short version's "faster" cells, at p95, as the table says them
  const leads = glance.flatMap(([r, c]) => {
    const p = find(r, c, "postgres", "mix")?.p95Ms ?? NaN, m = find(r, c, "mason", "mix")?.p95Ms ?? NaN;
    return Number.isFinite(p) && Number.isFinite(m) && m > 0 && m < p ? [p / m] : [];
  });
  const ratioText = (x: number): string => `${x < 9.95 ? x.toFixed(1) : x.toFixed(0)}×`;
  const [lo, hi] = [ratioText(Math.min(...leads)), ratioText(Math.max(...leads))];
  const lead = "The benchmark runs a dashboard's queries, such as a sum by status over every order, the top N orders joined to their customers, and a group-by over a JSON field. " + (leads.length === 0
    ? "Here is how Mason compares with Postgres at p95, as the tables grow and as more dashboards query at once:"
    : `At p95, Mason answers them ${lo === hi ? lo : `${lo} to ${hi}`} faster than Postgres. Mason keeps that lead as the tables grow and as more dashboards query at once:`);

  const headline = `${HEADLINE_START}
${lead}

${shortTable}

${shortNote("docs/DESIGN.md")} Each p95 is over a mix of ${f.queries.length} dashboard queries. It was measured on ${env.label}, against ${pgVersion}, ${env.postgres.where}. [docs/MEASUREMENTS.md](docs/MEASUREMENTS.md) has every measurement and how it was taken.
`;

  const section = `${START}
> **The numbers are a measurement; the sentences are a template.** \`tests/bench-replica.test.ts\` renders this section
> from \`tests/fixtures/bench-replica.json\`, a run of \`scripts/bench-replica.ts\`, and CI holds the section equal to what
> they render. To change the wording, edit the renderer; to change the numbers, run the benchmark
> ([docs/BENCHMARK.md](BENCHMARK.md)); an edit made here is undone by the next \`UPDATE_FIXTURE=1 npm run check\`.

A Postgres read replica answers a dashboard's SQL as Postgres does, and so does Mason: the same statements, the same
answers. The difference is what an answer costs as the tables grow and as more readers ask at once.

## The short version

${shortTable}

${shortNote("DESIGN.md")}

## As the tables grow

${rowsContext}

${rowsTable}${verdict(rowsSweep)}

## As more readers ask at once

${clientsContext}

${clientsTable}${connections}${verdict(clientsSweep)}
${otherCells}
## Statement by statement

**At ${rowsText(largest)} rows and ${clientsText(at)}**, each statement inside the mix; the last column is from the p50s.

${perQueryTable}

${winsNote}

## The first sync

**Mason's first sync** of each size, from that Postgres: *synced in* is the time until the synced tables were served,
and the JSON path is stored that long after its first reads.

${copyTable}

<details><summary>How it was measured</summary>

${measured}

</details>
`;
  return { section, headline };
}

