  assert.match(text, /\*\*At 50,000,000 orders\*\*, the largest size measured\.\n\n\| clients \|[^\n]*\n\|[^\n]*\n\| 4 \|[^\n]*\n\| 64 \|/);
  assert.match(text, /### Every other cell measured\n\n\| rows \| clients \|[^\n]*\n\|[^\n]*\n\| 10,000,000 \| 64 \| 2\.06 \| 0\.14 \| 15× faster \|/, "a cell on neither line is not lost");
  assert.match(text, /\| 10 M rows, 4 clients \| 2\.06 \| 0\.14 \| 15× faster \|\n\| 50 M rows, 4 clients \|[^\n]*\n\| 50 M rows, 64 clients \|/, "the short version: the first and last along the rows, the last along the clients");
