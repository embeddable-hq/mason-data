/** The product catalogue: its prices in cents, by id (1-based), which the orders' items read. */
function products(rand: () => number): Array<{ name: string; category: string; cents: number }> {
  const names = Object.keys(CATEGORIES);
  const out: Array<{ name: string; category: string; cents: number }> = [];
  for (let i = 0; i < SEED_COUNTS.products; i++) {
    const category = names[i % names.length]!;
    const c = CATEGORIES[category]!;
    const noun = c.nouns[Math.floor(i / names.length) % c.nouns.length]!;
    const adjective = ADJECTIVES[Math.floor(i / (names.length * c.nouns.length)) % ADJECTIVES.length]!;
    // a price ending in 99 or 49, as a shop's do
    const cents = Math.floor((c.cents[0] + rand() * (c.cents[1] - c.cents[0])) / 100) * 100 + (rand() < 0.7 ? 99 : 49);
    out.push({ name: `${adjective} ${noun}`, category, cents });
  }
  return out;
}

/** The status of an order placed `ageDays` ago: the old ones delivered (some cancelled), the newest still moving. */
function statusOf(ageDays: number, rand: () => number): string {
  if (rand() < 0.04) return "cancelled";
  if (ageDays > 10) return "delivered";
  if (ageDays > 5) return rand() < 0.6 ? "delivered" : "shipped";
  if (ageDays > 2) return rand() < 0.5 ? "shipped" : "paid";
  return rand() < 0.5 ? "paid" : "pending";
}

/**
 * The whole seed, as statements to run in order in ONE transaction: the tables, their rows, the identity sequences moved
 * past the ids written, and ANALYZE (run by the caller, outside the transaction) so the catalog's row estimates are the
 * counts. `now` anchors the dates: the orders span the 365 days before it.
 */
export function seedStatements(now: Date): { ddl: string; rows: string[]; after: string[] } {
  const rand = mulberry32(20_261_027);
  const end = now.getTime();
  const start = end - 365 * DAY_MS;

  const customerRows: string[] = [];
  const customerSince: number[] = [];
  for (let id = 1; id <= SEED_COUNTS.customers; id++) {
    const first = FIRST[Math.floor(rand() * FIRST.length)]!;
    const last = LAST[Math.floor(rand() * LAST.length)]!;
    const country = COUNTRIES[Math.floor(rand() * COUNTRIES.length)]!;
    // customers sign up over the year before the first orders and the year itself
    const since = start - 180 * DAY_MS + Math.floor(rand() * 500 * DAY_MS);
    customerSince.push(Math.min(since, end - DAY_MS));
    customerRows.push(`(${id}, ${lit(`${first} ${last}`)}, ${lit(`${first}.${last}.${id}@example.com`.toLowerCase())}, ${lit(country)}, ${stamp(customerSince[id - 1]!)})`);
  }

  const catalogue = products(rand);
  const productRows = catalogue.map((p, i) => `(${i + 1}, ${lit(p.name)}, ${lit(p.category)}, ${money(p.cents)})`);

  // the orders' times: more of them as the year goes on (a growing shop), sorted so ids follow time, as an app's do
  const times: number[] = [];
  for (let i = 0; i < SEED_COUNTS.orders; i++) times.push(start + Math.floor(Math.sqrt(rand()) * (end - start - 60_000)));
  times.sort((a, b) => a - b);
  const orderRows: string[] = [];
  const itemRows: string[] = [];
  let itemId = 0;
  for (let i = 0; i < times.length; i++) {
    const id = i + 1;
    const at = times[i]!;
    // a customer who had signed up by then; a few customers order far more often (the square skews to low ids)
    let customer = 1 + Math.floor(rand() * rand() * SEED_COUNTS.customers);
    if (customerSince[customer - 1]! > at) customer = 1 + Math.floor(rand() * SEED_COUNTS.customers);
    const lines = 1 + Math.floor(rand() * 5);   // 1–5 items, about 3 on average
    let total = 0;
    for (let l = 0; l < lines; l++) {
      const product = 1 + Math.floor(rand() * catalogue.length);
      const quantity = rand() < 0.75 ? 1 : 2 + Math.floor(rand() * 3);
      const cents = catalogue[product - 1]!.cents;
      total += quantity * cents;
      itemRows.push(`(${++itemId}, ${id}, ${product}, ${quantity}, ${money(cents)})`);
    }
    orderRows.push(`(${id}, ${customer}, ${lit(statusOf((end - at) / DAY_MS, rand))}, ${money(total)}, ${stamp(at)})`);
  }

  return {
    ddl: DDL,
    rows: [
      ...inserts("customers", "id, name, email, country, created_at", customerRows),
      ...inserts("products", "id, name, category, price", productRows),
      ...inserts("orders", "id, customer_id, status, total, created_at", orderRows),
      ...inserts("order_items", "id, order_id, product_id, quantity, unit_price", itemRows),
    ],
    // the identity columns continue past the ids written, so a later insert (`changeSql`) takes the next one
    after: DEMO_TABLES.map((t) => `SELECT setval(pg_get_serial_sequence('${t}', 'id'), (SELECT max(id) FROM ${t}))`),
  };
}

/** What one round of changes reads first: the newest order's id, the products' prices, and the oldest order still moving. */
export const CHANGE_STATE_SQL = `SELECT (SELECT coalesce(max(id), 0) FROM orders)::text AS newest,
  (SELECT count(*) FROM customers)::text AS customers,
  (SELECT coalesce(json_agg(json_build_array(id, (price * 100)::bigint) ORDER BY id), '[]'::json)::text FROM products) AS prices,
  (SELECT json_build_array(id, status)::text FROM orders WHERE status IN ('pending', 'paid', 'shipped') ORDER BY created_at, id LIMIT 1) AS moving`;

export interface ChangeState { newest: number; customers: number; prices: Array<[number, number]>; moving: [number, string] | null }

/**
 * ONE ROUND OF CHANGES, as one transaction's statements: a new order (now, `pending`) with 1–4 items and its total, and
 * the oldest order still moving moved one step on its path (pending → paid → shipped → delivered). Its values are drawn
 * from a PRNG seeded by the newest order's id, so the rounds are the same sequence on every demo. Answers the statements
 * (the new order's id read back last, as `id`) and what they did, in one line, given that id.
 */
export function changeSql(s: ChangeState): { statements: string[]; said: (orderId: string) => string } {
  const rand = mulberry32(s.newest * 7_919 + 17);
  const customer = 1 + Math.floor(rand() * Math.max(1, s.customers));
  const lines = 1 + Math.floor(rand() * 4);
  const items: Array<{ product: number; quantity: number; cents: number }> = [];
  for (let l = 0; l < lines && s.prices.length > 0; l++) {
    const [product, cents] = s.prices[Math.floor(rand() * s.prices.length)]!;
    items.push({ product, quantity: rand() < 0.75 ? 1 : 2, cents });
  }
  const total = items.reduce((sum, i) => sum + i.quantity * i.cents, 0);
  const statements = [
    // the order's id is its identity's next, read back by the items through currval
    `INSERT INTO orders (customer_id, status, total, created_at) VALUES (${customer}, 'pending', ${money(total)}, now())`,
    ...(items.length === 0 ? [] : [`INSERT INTO order_items (order_id, product_id, quantity, unit_price) VALUES ` +
      items.map((i) => `(currval(pg_get_serial_sequence('orders', 'id')), ${i.product}, ${i.quantity}, ${money(i.cents)})`).join(", ")]),
  ];
  let moved = "";
  if (s.moving !== null) {
    const [id, status] = s.moving;
    const next = ORDER_STATUSES[ORDER_STATUSES.indexOf(status as (typeof ORDER_STATUSES)[number]) + 1];
    if (next !== undefined) {
      statements.push(`UPDATE orders SET status = ${lit(next)} WHERE id = ${id}`);
      moved = `; order ${id} ${status} → ${next}`;
    }
  }
  statements.push(`SELECT currval(pg_get_serial_sequence('orders', 'id'))::text AS id`);
  return {
    statements,
    said: (orderId) => `order ${orderId} placed by customer ${customer} (${items.length} item${items.length === 1 ? "" : "s"}, ${money(total)})${moved}`,
  };
}
