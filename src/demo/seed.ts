/**
 * THE DEMO DATABASE'S SCHEMA AND ROWS (`mason init demo`, src/demo/source.ts): a small web shop a BI user recognises at
 * once — `customers`, `products`, `orders`, `order_items` — with primary and foreign keys declared, about 200 / 50 /
 * 5,000 / 15,000 rows, and the orders' dates spread over the twelve months before the seed, so a time-window chart has
 * data in every week.
 *
 * SYNTHETIC ONLY (CLAUDE.md "A real database's data and structures are confidential"): every name below is made up
 * here, from short word lists, and every email is at example.com.
 *
 * DETERMINISTIC: one seeded PRNG (`mulberry32`) draws every value, so every demo holds the same rows; only the dates are
 * anchored to the moment of the seed (`now`), so "the last 30 days" has orders whenever the demo was made. The rounds of
 * changes (`changeSql`) draw from a PRNG seeded by the newest order's id, so they are the same sequence too, across
 * restarts.
 *
 * WRITTEN AS A FEW MULTI-ROW INSERTs (`ROWS_PER_INSERT` a statement), never one per row: PGlite is slow per statement.
 * Prices and totals are counted in integer cents and printed as decimals, so a total is exactly its items' sum.
 */

/** A small, fast, seeded PRNG (mulberry32): the same seed, the same sequence, on every machine. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

